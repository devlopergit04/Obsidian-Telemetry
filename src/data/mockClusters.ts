export function createLiveLogEntry(cluster: ClusterData): LogEntry {
  const samplePod = cluster.pods[Math.floor(Math.random() * cluster.pods.length)];
  const sampleNode =
    cluster.nodes.find((n) => n.id === samplePod?.nodeId) || cluster.nodes[0];
  const roll = Math.random();
  const level =
    roll > 0.88
      ? LogLevel.ERROR
      : roll > 0.7
      ? LogLevel.WARN
      : roll > 0.52
      ? LogLevel.TRACE
      : LogLevel.INFO;

  const traceHex = Math.random().toString(16).substring(2, 10);
  const now = new Date().toISOString();

  const messagesByLevel: Record<LogLevel, string[]> = {
    [LogLevel.INFO]: [
      `gRPC health probe succeeded upstream=${samplePod?.ip || '10.244.1.12'}:8080 rtt=${(2 + Math.random() * 8).toFixed(1)}ms`,
      `eBPF cilium policy map synced revision=${Math.floor(1400 + Math.random() * 500)} entries=428`,
      `HTTP/2 request completed status=200 latency=${(4 + Math.random() * 14).toFixed(1)}ms`,
    ],
    [LogLevel.WARN]: [
      `goroutine scheduler queue latency spiked to ${(18 + Math.random() * 30).toFixed(1)}ms`,
      `upstream connection retry #1 target=${samplePod?.ip || '10.244.2.91'}:5432`,
      `cgroup memory working_set at 84.2% of limit`,
    ],
    [LogLevel.ERROR]: [
      `context deadline exceeded awaiting raft commit from ${sampleNode?.ip || '10.240.14.88'}`,
      `upstream reset stream error_code=NO_ERROR reset_reason=connection_termination`,
    ],
    [LogLevel.TRACE]: [
      `span_export batch=128 compressed_bytes=14280 collector_rtt=3.1ms`,
      `tls_session_ticket_rotated cipher=TLS_AES_256_GCM_SHA384`,
    ],
  };

  const candidates = messagesByLevel[level];
  const message = candidates[Math.floor(Math.random() * candidates.length)];

  return {
    id: `log-live-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    timestamp: now,
    level,
    service: samplePod ? samplePod.name.split('-').slice(0, 2).join('-') : 'kube-apiserver',
    pod: samplePod?.name || 'kube-apiserver-01',
    nodeHostname: sampleNode?.hostname || 'control-plane-01',
    traceId: `tr-${traceHex}`,
    message,
    payload:
      level === LogLevel.ERROR
        ? `{"node":"${sampleNode?.ip}","pod":"${samplePod?.name}","retryable":true}`
        : undefined,
  };
}
