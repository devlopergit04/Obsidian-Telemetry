const TIMESTAMPS_15 = [
  '04:14:00',
  '04:15:00',
  '04:16:00',
  '04:17:00',
  '04:18:00',
  '04:19:00',
  '04:20:00',
  '04:21:00',
  '04:22:00',
  '04:23:00',
  '04:24:00',
  '04:25:00',
  '04:26:00',
  '04:27:00',
  '04:28:00',
];

function buildSeries(
  cpuBase: number,
  memBase: number,
  netBase: number,
  latBase: number,
  spikeIndex?: number
) {
  return TIMESTAMPS_15.map((ts, idx) => {
    const wave = Math.sin(idx * 0.7) * 4 + Math.cos(idx * 1.1) * 2.5;
    const isSpike = spikeIndex !== undefined && Math.abs(idx - spikeIndex) <= 1;
    const spikeBoost = isSpike ? 16 : 0;
    return {
      timestamp: ts,
      cpu: Math.min(98, Math.max(12, Math.round((cpuBase + wave + spikeBoost) * 10) / 10)),
      memory: Math.min(96, Math.max(24, Math.round((memBase + wave * 0.6 + spikeBoost * 0.4) * 10) / 10)),
      networkMbps: Math.max(120, Math.round(netBase + wave * 28 + spikeBoost * 32)),
      p99LatencyMs: Math.max(4.2, Math.round((latBase + Math.abs(wave) * 0.9 + (isSpike ? 24 : 0)) * 10) / 10),
    };
  });
}

export function generateWindowSeries(
  currentSeries: { cpu: number; memory: number; networkMbps: number; p99LatencyMs: number }[],
  windowSize: '15m' | '1h' | '6h' | '24h'
) {
  const latest = currentSeries[currentSeries.length - 1] || {
    cpu: 55,
    memory: 64,
    networkMbps: 1600,
    p99LatencyMs: 12,
  };
  const stepMinutes =
    windowSize === '15m' ? 1 : windowSize === '1h' ? 4 : windowSize === '6h' ? 24 : 96;
  const now = new Date();
  const count = 15;

  return Array.from({ length: count }, (_, idx) => {
    const offsetMin = (count - 1 - idx) * stepMinutes;
    const t = new Date(now.getTime() - offsetMin * 60_000);
    const ts = t.toISOString().slice(11, 19);
    const phase = idx * (windowSize === '15m' ? 0.6 : windowSize === '1h' ? 0.85 : 1.1);
    const amp = windowSize === '15m' ? 3.5 : windowSize === '1h' ? 5.5 : 8.5;
    const wave = Math.sin(phase) * amp + Math.cos(phase * 0.7) * (amp * 0.5);

    if (idx === count - 1) {
      return {
        timestamp: ts,
        cpu: latest.cpu,
        memory: latest.memory,
        networkMbps: latest.networkMbps,
        p99LatencyMs: latest.p99LatencyMs,
      };
    }

    return {
      timestamp: ts,
      cpu: Math.min(98, Math.max(12, Math.round((latest.cpu + wave - 2) * 10) / 10)),
      memory: Math.min(96, Math.max(22, Math.round((latest.memory + wave * 0.45) * 10) / 10)),
      networkMbps: Math.max(150, Math.round(latest.networkMbps + wave * 35)),
      p99LatencyMs: Math.max(3.5, Math.round((latest.p99LatencyMs + Math.abs(wave) * 0.7) * 10) / 10),
    };
  });
}

